/// UserProfileDialog displays account info in English (LTR), allows editing
/// Full Name & Email Address, changing password, viewing security audit logs,
/// and switching RBAC roles using Material Design 3 standards.
class UserProfileDialog extends StatefulWidget {
  final ApiClient apiClient;
  final String tenantSlug;
  final VoidCallback? onLogout;
  final VoidCallback? onRoleChanged;

  const UserProfileDialog({
    super.key,
    required this.apiClient,
    required this.tenantSlug,
    this.onLogout,
    this.onRoleChanged,
  });

  @override
  State<UserProfileDialog> createState() => _UserProfileDialogState();
}

class _RbacPersonaOption {
  final String id;
  final String label;
  final String subtitle;
  final String role;
  final String? assignedChain;
  final String? assignedRegion;

  const _RbacPersonaOption({
    required this.id,
    required this.label,
    required this.subtitle,
    required this.role,
    this.assignedChain,
    this.assignedRegion,
  });
}

class _UserProfileDialogState extends State<UserProfileDialog> {
  late final TextEditingController _nameController;
  late final TextEditingController _emailController;
  final _oldPasswordController = TextEditingController();
  final _newPasswordController = TextEditingController();
  final _confirmPasswordController = TextEditingController();

  bool _isEditingProfile = false;
  bool _isChangingPassword = false;
  bool _isLoading = false;

  static const List<_RbacPersonaOption> _personas = [
    _RbacPersonaOption(
      id: 'vendor_admin',
      label: 'Vendor Admin',
      subtitle: 'Full access: file uploads, report exports, and audit logs',
      role: 'vendor_admin',
    ),
    _RbacPersonaOption(
      id: 'sales_director',
      label: 'Sales Director',
      subtitle: 'All chains & regions: view and export financial analytics',
      role: 'sales_director',
    ),
    _RbacPersonaOption(
      id: 'chain_kam_carrefour',
      label: 'Chain KAM (Carrefour)',
      subtitle: 'Restricted to Carrefour chain with NDA competitor masking',
      role: 'chain_kam',
      assignedChain: 'carrefour',
    ),
    _RbacPersonaOption(
      id: 'chain_kam_fathalla',
      label: 'Chain KAM (Fathalla)',
      subtitle: 'Restricted to Fathalla chain with NDA competitor masking',
      role: 'chain_kam',
      assignedChain: 'fathalla',
    ),
    _RbacPersonaOption(
      id: 'field_supervisor_alex',
      label: 'Field Supervisor (Alexandria)',
      subtitle: 'Restricted to East Alexandria region (no financial exports or uploads)',
      role: 'field_supervisor',
      assignedRegion: 'شرق الإسكندرية',
    ),
  ];

  static const Set<String> _legacyAutoGeneratedNames = {
    'مدير العمليات',
    'مدير الشركة الموردة',
    'مدير الشركة (Vendor Admin)',
    'مدير المبيعات والتطوير التجاري (Sales Director)',
    'مدير حساب السلسلة (Chain KAM - كارفور)',
    'مدير حساب السلسلة (Chain KAM - فتح الله)',
    'مشرف ميداني وتشغيلي (Field Supervisor - الإسكندرية)',
    'مشرف ميداني (Field Supervisor)',
    'Vendor Admin',
    'Sales Director',
    'Chain KAM (Carrefour)',
    'Chain KAM (Fathalla)',
    'Field Supervisor (Alexandria)',
  };

  @override
  void initState() {
    super.initState();
    final cleanSlug = ApiClient.normalizeDataTenantSlug(widget.tenantSlug);
    final companyEn = ApiClient.getEnglishDisplayNameForTenant(cleanSlug);
    final user = widget.apiClient.currentUser;
    final resolvedName = _resolveCleanDisplayName(user?.fullName, companyEn);
    final resolvedEmail = (user?.email != null && user!.email.trim().isNotEmpty)
        ? user.email.trim()
        : 'admin@$cleanSlug-retail.com';

    _nameController = TextEditingController(text: resolvedName);
    _emailController = TextEditingController(text: resolvedEmail);
  }

  @override
  void dispose() {
    _nameController.dispose();
    _emailController.dispose();
    _oldPasswordController.dispose();
    _newPasswordController.dispose();
    _confirmPasswordController.dispose();
    super.dispose();
  }

  String _resolveCleanDisplayName(String? rawName, String companyEn) {
    final trimmed = (rawName ?? '').trim();
    if (trimmed.isEmpty) return '$companyEn Admin';
    if (_legacyAutoGeneratedNames.contains(trimmed) ||
        trimmed.startsWith('مدير عمليات') ||
        trimmed.startsWith('مدير ') ||
        trimmed.startsWith('مشرف ميداني')) {
      return '$companyEn Admin';
    }
    return trimmed;
  }

  void _applyPersona(_RbacPersonaOption persona) {
    final existing = widget.apiClient.currentUser;
    final cleanSlug = ApiClient.normalizeDataTenantSlug(widget.tenantSlug);
    final companyEn = ApiClient.getEnglishDisplayNameForTenant(cleanSlug);
    final preservedName = _resolveCleanDisplayName(
      _nameController.text.isNotEmpty ? _nameController.text : existing?.fullName,
      companyEn,
    );
    final preservedEmail = _emailController.text.trim().isNotEmpty
        ? _emailController.text.trim()
        : (existing?.email ?? 'admin@$cleanSlug-retail.com');

    final updated = TenantUserModel(
      userId: existing?.userId ?? 'user-$cleanSlug-${persona.id}',
      tenantId: existing?.tenantId ?? cleanSlug,
      email: preservedEmail,
      fullName: preservedName,
      role: persona.role,
      assignedChain: persona.assignedChain,
      assignedRegion: persona.assignedRegion,
    );
    setState(() {
      widget.apiClient.currentUser = updated;
    });
    widget.apiClient.updateUserProfile(
      fullName: preservedName,
      email: preservedEmail,
    );
    widget.apiClient.recordAuditLog(
      action: 'RBAC_ROLE_SWITCH',
      resource: 'user_profile_dialog',
      details: 'Switched active RBAC role to: ${persona.label}',
    );
    widget.onRoleChanged?.call();
    M3Feedback.showSuccess(
      context,
      'Active role switched to ${persona.label}',
    );
  }

  bool _isPersonaSelected(_RbacPersonaOption persona, TenantUserModel? user) {
    final activeRole = user?.role ?? 'vendor_admin';
    if (activeRole != persona.role) return false;
    if (persona.role == 'chain_kam') {
      return (user?.assignedChain ?? 'carrefour').toLowerCase() ==
          (persona.assignedChain ?? '').toLowerCase();
    }
    if (persona.role == 'field_supervisor') {
      return (user?.assignedRegion ?? 'شرق الإسكندرية') ==
          persona.assignedRegion;
    }
    return true;
  }

  String _formatScopeLabelEn(TenantUserModel? user) {
    if (user == null) return 'All Chains & Regions';
    if (user.role == 'chain_kam' &&
        user.assignedChain != null &&
        user.assignedChain!.isNotEmpty) {
      final chainLower = user.assignedChain!.toLowerCase();
      final chainEn = chainLower == 'carrefour'
          ? 'Carrefour'
          : chainLower == 'fathalla'
              ? 'Fathalla'
              : ApiClient.formatBrandTitle(chainLower);
      return '$chainEn Chain';
    }
    if (user.role == 'field_supervisor' &&
        user.assignedRegion != null &&
        user.assignedRegion!.isNotEmpty) {
      final reg = user.assignedRegion!;
      if (reg.contains('الإسكندرية')) {
        return 'East Alexandria Region';
      }
      return reg;
    }
    return 'All Chains & Regions';
  }

  Future<void> _submitProfileUpdate() async {
    final newName = _nameController.text.trim();
    final newEmail = _emailController.text.trim();

    if (newName.isEmpty) {
      M3Feedback.showError(context, 'Please enter a valid full name');
      return;
    }
    if (newEmail.isEmpty || !newEmail.contains('@')) {
      M3Feedback.showError(context, 'Please enter a valid email address');
      return;
    }

    setState(() => _isLoading = true);
    await widget.apiClient.updateUserProfile(
      fullName: newName,
      email: newEmail,
    );

    if (mounted) {
      setState(() {
        _isLoading = false;
        _isEditingProfile = false;
      });
      widget.onRoleChanged?.call();
      M3Feedback.showSuccess(context, 'Profile updated successfully');
    }
  }

  Future<void> _submitChangePassword() async {
    final oldPass = _oldPasswordController.text.trim();
    final newPass = _newPasswordController.text.trim();
    final confirmPass = _confirmPasswordController.text.trim();

    if (oldPass.isEmpty || newPass.isEmpty) {
      M3Feedback.showError(context, 'Please enter current and new passwords');
      return;
    }
    if (newPass.length < 8) {
      M3Feedback.showError(context, 'New password must be at least 8 characters');
      return;
    }
    if (newPass != confirmPass) {
      M3Feedback.showError(context, 'New password and confirmation do not match');
      return;
    }

    setState(() => _isLoading = true);
    try {
      await widget.apiClient.changePassword(
        oldPassword: oldPass,
        newPassword: newPass,
      );
      if (mounted) {
        setState(() {
          _isLoading = false;
          _isChangingPassword = false;
          _oldPasswordController.clear();
          _newPasswordController.clear();
          _confirmPasswordController.clear();
        });
        M3Feedback.showSuccess(context, 'Password updated successfully');
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isLoading = false);
        M3Feedback.showError(context, e.toString());
      }
    }
  }

