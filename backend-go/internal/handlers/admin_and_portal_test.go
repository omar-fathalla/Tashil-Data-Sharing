func TestPortalMetaEndpoint(t *testing.T) {
	fsClient := firestore.NewClient("test-db", true)
	portalHandler := NewPortalHandler(fsClient)

	// 1. Adeco Portal Meta
	req := httptest.NewRequest(http.MethodGet, "/api/v1/portal/adeco/meta", nil)
	req.SetPathValue("slug", "adeco")
	rec := httptest.NewRecorder()

	portalHandler.HandleGetPortalMeta(rec, req)

	if rec.Code != http.StatusOK {
		t.Fatalf("expected HTTP 200, got %d", rec.Code)
	}

	var meta domain.TenantMetaResponse
	if err := json.NewDecoder(rec.Body).Decode(&meta); err != nil {
		t.Fatalf("failed to decode meta: %v", err)
	}

	if meta.Slug != "adeco" {
		t.Errorf("expected slug adeco, got %s", meta.Slug)
	}
	if meta.BrandSeedColor != "#35A211" {
		t.Errorf("expected seed color #35A211, got %s", meta.BrandSeedColor)
	}

	// 2. Non-existent slug returns 404
	req404 := httptest.NewRequest(http.MethodGet, "/api/v1/portal/unknown/meta", nil)
	req404.SetPathValue("slug", "unknown")
	rec404 := httptest.NewRecorder()

	portalHandler.HandleGetPortalMeta(rec404, req404)
	if rec404.Code != http.StatusNotFound {
		t.Fatalf("expected HTTP 404, got %d", rec404.Code)
	}
}

func TestSuperAdminTenantProvisioningWizard(t *testing.T) {
	fsClient := firestore.NewClient("test-db", true)
	authMW := middleware.NewAuthMiddleware("test-secret", true)
	adminHandler := NewAdminHandler(fsClient)
	authHandler := NewAuthHandler(fsClient, authMW)

	// Create new tenant payload
	createBody, _ := json.Marshal(domain.CreateTenantRequest{
		DisplayName:    "شركة جهينة للصناعات الغذائية (Juhayna)",
		Slug:           "juhayna",
		BrandSeedColor: "#059669",
		AdminEmail:     "admin@juhayna-dairy.com",
		AdminName:      "كريم المصري",
		ActiveChains:   []string{"carrefour", "fathalla", "gomla"},
	})

	req := httptest.NewRequest(http.MethodPost, "/api/v1/admin/tenants", bytes.NewReader(createBody))
	// Authenticate as Super Admin
	superClaims := &domain.UserClaims{
		UserID:   "user-super-admin",
		TenantID: "system",
		Email:    "admin@tashil.com",
		Role:     domain.RoleSuperAdmin,
		Name:     "مدير عام منصة تسهيل",
	}
	ctx := context.WithValue(req.Context(), middleware.UserClaimsContextKey, superClaims)
	req = req.WithContext(ctx)

	rec := httptest.NewRecorder()
	adminHandler.HandleCreateTenant(rec, req)

	if rec.Code != http.StatusCreated {
		t.Fatalf("expected HTTP 201 Created, got %d: %s", rec.Code, rec.Body.String())
	}

	var createResp domain.CreateTenantResponse
	if err := json.NewDecoder(rec.Body).Decode(&createResp); err != nil {
		t.Fatalf("failed to decode response: %v", err)
	}

	if createResp.Tenant.Slug != "juhayna" {
		t.Errorf("expected slug juhayna, got %s", createResp.Tenant.Slug)
	}
	if createResp.PortalURL != "http://localhost:3000/portal/juhayna" {
		t.Errorf("expected portal URL http://localhost:3000/portal/juhayna, got %s", createResp.PortalURL)
	}
	if createResp.TemporaryPassword == "" {
		t.Fatalf("expected auto-generated temporary password")
	}

	// Verify the newly provisioned tenant's admin can immediately log in
	loginBody, _ := json.Marshal(domain.LoginRequest{
		TenantID: "juhayna",
		Email:    "admin@juhayna-dairy.com",
		Password: createResp.TemporaryPassword,
	})

	reqLogin := httptest.NewRequest(http.MethodPost, "/api/v1/auth/login", bytes.NewReader(loginBody))
	recLogin := httptest.NewRecorder()
	authHandler.HandleLogin(recLogin, reqLogin)

	if recLogin.Code != http.StatusOK {
		t.Fatalf("expected new admin to login with temporary password, got %d: %s", recLogin.Code, recLogin.Body.String())
	}

	// Super Admin force resets password for tenant
	resetReq := httptest.NewRequest(http.MethodPost, "/api/v1/admin/tenants/juhayna/reset-password", bytes.NewReader([]byte(`{}`)))
	resetReq.SetPathValue("id", "juhayna")
	resetReq = resetReq.WithContext(ctx)
	recReset := httptest.NewRecorder()

	adminHandler.HandleResetTenantPassword(recReset, resetReq)
	if recReset.Code != http.StatusOK {
		t.Fatalf("expected HTTP 200 on admin reset password, got %d", recReset.Code)
	}

	var resetResp domain.AdminResetPasswordResponse
	_ = json.NewDecoder(recReset.Body).Decode(&resetResp)
	if resetResp.TemporaryPassword == "" {
		t.Fatalf("expected new temporary password generated by admin reset")
	}
}

func TestRLSCrossTenantEnforcement(t *testing.T) {
	// Adeco vendor admin context
	adecoClaims := &domain.UserClaims{
		UserID:   "user-adeco-01",
		TenantID: "adeco",
		Email:    "user@adeco.com",
		Role:     domain.RoleVendorAdmin,
	}
	ctxAdeco := context.WithValue(context.Background(), middleware.UserClaimsContextKey, adecoClaims)

	// Adeco accessing adeco -> OK
	if err := middleware.AssertTenantMatch(ctxAdeco, "adeco"); err != nil {
		t.Errorf("expected access to own tenant to succeed, got %v", err)
	}
	if err := middleware.AssertTenantMatch(ctxAdeco, "tenant-adeco"); err != nil {
		t.Errorf("expected normalized access to succeed, got %v", err)
	}

	// Adeco accessing Unilever -> must fail with ErrTenantForbidden
	err := middleware.AssertTenantMatch(ctxAdeco, "unilever")
	if err == nil {
		t.Errorf("expected cross-tenant access to fail")
	}

	// Super Admin context can access any tenant
	superClaims := &domain.UserClaims{
		UserID:   "user-super-admin",
		TenantID: "system",
		Email:    "admin@tashil.com",
		Role:     domain.RoleSuperAdmin,
	}
	ctxSuper := context.WithValue(context.Background(), middleware.UserClaimsContextKey, superClaims)

	if err := middleware.AssertTenantMatch(ctxSuper, "unilever"); err != nil {
		t.Errorf("expected super admin to access unilever tenant, got %v", err)
	}
	if err := middleware.AssertTenantMatch(ctxSuper, "adeco"); err != nil {
		t.Errorf("expected super admin to access adeco tenant, got %v", err)
	}
}

