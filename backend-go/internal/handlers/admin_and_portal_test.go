func TestAdminEndpointsRejectNonSuperAdmin(t *testing.T) {
	fsClient := firestore.NewClient("test-db", true)
	adminHandler := NewAdminHandler(fsClient)

	// 1. Vendor Admin attempt on GET /api/v1/admin/tenants -> 403
	reqList := httptest.NewRequest(http.MethodGet, "/api/v1/admin/tenants", nil)
	vendorClaims := &domain.UserClaims{
		UserID:   "user-adeco-01",
		TenantID: "adeco",
		Email:    "admin@adeco-retail.com",
		Role:     domain.RoleVendorAdmin,
	}
	reqList = reqList.WithContext(context.WithValue(reqList.Context(), middleware.UserClaimsContextKey, vendorClaims))
	recList := httptest.NewRecorder()
	adminHandler.HandleListTenants(recList, reqList)

	if recList.Code != http.StatusForbidden {
		t.Fatalf("expected HTTP 403 Forbidden for vendor admin listing tenants, got %d", recList.Code)
	}

	// 2. Vendor Admin attempt on POST /api/v1/admin/tenants -> 403
	reqCreate := httptest.NewRequest(http.MethodPost, "/api/v1/admin/tenants", bytes.NewReader([]byte(`{"display_name":"Test"}`)))
	reqCreate = reqCreate.WithContext(context.WithValue(reqCreate.Context(), middleware.UserClaimsContextKey, vendorClaims))
	recCreate := httptest.NewRecorder()
	adminHandler.HandleCreateTenant(recCreate, reqCreate)

	if recCreate.Code != http.StatusForbidden {
		t.Fatalf("expected HTTP 403 Forbidden for vendor admin creating tenant, got %d", recCreate.Code)
	}

	// 3. Unauthenticated request (no claims) -> 403
	reqUnauth := httptest.NewRequest(http.MethodGet, "/api/v1/admin/tenants", nil)
	recUnauth := httptest.NewRecorder()
	adminHandler.HandleListTenants(recUnauth, reqUnauth)

	if recUnauth.Code != http.StatusForbidden {
		t.Fatalf("expected HTTP 403 Forbidden for unauthenticated request, got %d", recUnauth.Code)
	}
}
